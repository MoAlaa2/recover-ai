_ARABIC_RE = re.compile(r"[؀-ۿݐ-ݿﭐ-﷿"
                        r"ﹰ-﻿]")
_FONTS = {}


def _font(arabic, size, bold=False):
    key = (arabic, size, bold)
    if key not in _FONTS:
        # Always the basic layout engine: with libraqm present (the
        # Modal image) Pillow would shape and reorder the Arabic a
        # second time on top of arabic_reshaper + bidi, which broke the
        # joins and reversed the words in the deployed PDF.
        layout = getattr(getattr(ImageFont, "Layout", None), "BASIC",
                         getattr(ImageFont, "LAYOUT_BASIC", 0))
        f = ImageFont.truetype(FONT_ARABIC if arabic else FONT_LATIN, size,
                               layout_engine=layout)
        if bold:
            try:
                f.set_variation_by_name("Bold")
            except Exception:  # noqa: BLE001 - static font: keep regular
                pass
        _FONTS[key] = f
    return _FONTS[key]


def arabic_digits(text):
    return str(text).translate(str.maketrans("0123456789", "٠١٢٣٤٥٦٧٨٩"))


def shape(text, lang):
    """Visual-order string for drawing (Arabic shaped + bidi)."""
    if lang != "ar" or not _ARABIC_RE.search(text):
        return text
    import arabic_reshaper
    from bidi.algorithm import get_display
    return get_display(arabic_reshaper.reshape(text))


def _runs(text):
    """Split visual-order text into (is_arabic, chunk) runs."""
    runs = []
    for ch in text:
        arabic = bool(_ARABIC_RE.match(ch))
        if runs and runs[-1][0] == arabic:
            runs[-1][1] += ch
        elif runs and ch in " ·—-–:/()" and not arabic:
            # Punctuation and spaces follow the previous run's font.
            runs[-1][1] += ch
        else:
            runs.append([arabic, ch])
    return runs


def text_width(text, size, bold=False):
    return sum(_font(a, size, bold).getlength(chunk) for a, chunk in
               _runs(text))


def draw_text(d, x, y, text, size, lang, bold=False, color=INK,
              align="left", max_width=None):
    """Draw one line; align is left/right/center in page coordinates.
    Returns the drawn width."""
    text = shape(str(text), lang)
    if max_width:
        while text_width(text, size, bold) > max_width and len(text) > 3:
            text = text[:-2] + "…" if lang != "ar" else text[2:]
    width = text_width(text, size, bold)
    if align == "right":
        x = x - width
    elif align == "center":
        x = x - width / 2.0
    cur = x
    for arabic, chunk in _runs(text):
        f = _font(arabic, size, bold)
        d.text((cur, y), chunk, font=f, fill=color)
        cur += f.getlength(chunk)
    return width


def fmt_num(value, lang, decimals=1):
    if value is None:
        return "—"
    num = float(value)
    text = ("%d" % round(num)) if abs(num - round(num)) < 0.05 and \
        decimals <= 1 else ("%%.%df" % decimals) % num
    if decimals == 2 and abs(num - round(num)) < 0.005:
        text = "%d" % round(num)
    if lang == "ar":
        return arabic_digits(text)
    return text


def _fit(img, box_w, box_h):
    im = img.convert("RGB").copy()
    im.thumbnail((box_w, box_h), Image.LANCZOS)
    canvas = Image.new("RGB", (box_w, box_h), SOFT)
    canvas.paste(im, ((box_w - im.width) // 2, (box_h - im.height) // 2))
    return canvas


def render_proposal(data, lang="en"):
    """data: {mode, prepared_by, before (PIL|None), after (PIL|None),
    items: [{label, name, code, material, price_usd_per_m, meters,
    line_total, swatch (PIL|None)}], total, co2: {kg, waste_kg, source}}.
    Returns PDF bytes."""
    lang = "ar" if lang == "ar" else "en"
    s = STRINGS[lang]
    rtl = lang == "ar"
    page = Image.new("RGB", (PAGE_W, PAGE_H), PAPER)
    d = ImageDraw.Draw(page)
    left, right = MARGIN, PAGE_W - MARGIN
    start, end = (right, left) if rtl else (left, right)
    a_main = "right" if rtl else "left"
    a_opp = "left" if rtl else "right"

    # Header
    y = MARGIN
    d.rectangle([left, y, left + 14, y + 44], fill=ACCENT)
    draw_text(d, left + 26, y - 4, "ReCover", 40, "en", bold=True)
    draw_text(d, right, y, s["title"], 30, lang, bold=True, align="right")
    today = datetime.date.today().isoformat()
    meta = "%s: %s" % (s["date"], today)
    if data.get("prepared_by"):
        meta += "   ·   %s: %s" % (s["prepared"], data["prepared_by"])
    draw_text(d, right, y + 46, meta, 18, lang, color=MUTED, align="right",
              max_width=PAGE_W - 2 * MARGIN - 260)
    y += 100
    d.line([left, y, right, y], fill=LINE, width=2)

    # Images
    y += 28
    plan_mode = data.get("mode") == "plan"
    cap_before = s["plan"] if plan_mode else s["before"]
    cap_after = s["render"] if plan_mode else s["after"]
    gap = 24
    box_w = (PAGE_W - 2 * MARGIN - gap) // 2
    box_h = int(box_w * 0.72)
    slots = [(data.get("before"), cap_before), (data.get("after"), cap_after)]
    if rtl:
        slots = slots[::-1]
    for i, (img, cap) in enumerate(slots):
        x = left + i * (box_w + gap)
        if img is not None:
            page.paste(_fit(img, box_w, box_h), (x, y))
        else:
            d.rectangle([x, y, x + box_w, y + box_h], fill=SOFT)
        d.rectangle([x, y, x + box_w, y + box_h], outline=LINE, width=2)
        draw_text(d, x + box_w - 12 if rtl else x + 12, y + box_h + 10,
                  cap, 18, lang, color=MUTED, align="right" if rtl
                  else "left", max_width=box_w - 24)
    y += box_h + 54

    # Items table
    draw_text(d, start, y, s["items"], 24, lang, bold=True, align=a_main)
    y += 44
    cols = {"item": 0.30, "fabric": 0.34, "meters": 0.10, "price": 0.12,
            "line": 0.14}
    width_total = PAGE_W - 2 * MARGIN
    xs = {}
    acc = 0.0
    for key in ("item", "fabric", "meters", "price", "line"):
        xs[key] = (left + acc * width_total, cols[key] * width_total)
        acc += cols[key]

    def col_x(key, align_end=False):
        x0, w = xs[key]
        if rtl:
            x0 = right - (x0 - left) - w
        return (x0 + w) if (align_end ^ rtl) else x0
    hdr_align = {"item": a_main, "fabric": a_main, "meters": a_opp,
                 "price": a_opp, "line": a_opp}
    for key in cols:
        draw_text(d, col_x(key, key in ("meters", "price", "line")), y,
                  s[key], 16, lang, color=MUTED, align=hdr_align[key])
    y += 30
    d.line([left, y, right, y], fill=LINE, width=1)
    items = data.get("items") or []
    if not items:
        y += 16
        draw_text(d, start, y, s["no_items"], 18, lang, color=MUTED,
                  align=a_main)
        y += 40
    for it in items:
        y += 14
        row_h = 72
        sw = it.get("swatch")
        tx = col_x("item")
        if sw is not None:
            thumb = _fit(sw, 56, 56)
            px = (col_x("item") - 56 - 12) if rtl else col_x("item")
            page.paste(thumb, (int(px), int(y) + 2))
            tx = (col_x("item") - 56 - 24) if rtl else col_x("item") + 56 + 12
        draw_text(d, tx, y, it.get("label", ""), 19, lang, bold=True,
                  align=a_main, max_width=xs["item"][1] - 80)
        draw_text(d, tx, y + 30, it.get("code", ""), 15, "en", color=MUTED,
                  align=a_main)
        draw_text(d, col_x("fabric"), y, it.get("name", ""), 19, lang,
                  align=a_main, max_width=xs["fabric"][1] - 16)
        draw_text(d, col_x("fabric"), y + 30, it.get("material", ""), 15,
                  lang, color=MUTED, align=a_main,
                  max_width=xs["fabric"][1] - 16)
        meters = it.get("meters")
        draw_text(d, col_x("meters", True), y + 6,
                  (fmt_num(meters, lang) + " " + s["m"]) if meters is not None
                  else "—", 18, lang, align=a_opp)
        price = it.get("price_usd_per_m")
        draw_text(d, col_x("price", True), y + 6,
                  fmt_num(price, lang) if price is not None else "—", 18,
                  lang, align=a_opp)
        line = it.get("line_total")
        draw_text(d, col_x("line", True), y + 6,
                  (fmt_num(line, lang, 2) + " " + s["sar"]) if line is not None
                  else "—", 18, lang, bold=True, align=a_opp)
        y += row_h
        d.line([left, y, right, y], fill=LINE, width=1)

    # Total
    y += 18
    total = data.get("total")
    if total is not None:
        amount = "%s %s" % (fmt_num(total, lang, 2), s["sar"])
        w = text_width(shape(amount, lang), 26, True)
        draw_text(d, end, y, amount, 26, lang, bold=True, align=a_opp)
        label_x = (left + w + 18) if rtl else (right - w - 18)
        draw_text(d, label_x, y + 6, s["total"], 18, lang, color=MUTED,
                  align="left" if rtl else "right")
    y += 46
    draw_text(d, start, y, s["preliminary"], 16, lang, color=MUTED,
              align=a_main)
    y += 40

    # CO2
    co2 = data.get("co2") or {}
    if co2.get("kg"):
        d.rectangle([left, y, right, y + 76], fill=SOFT)
        draw_text(d, start - (18 if rtl else -18), y + 12,
                  s["co2"] % (fmt_num(co2.get("kg"), lang),
                              fmt_num(co2.get("waste_kg"), lang)),
                  17, lang, align=a_main, max_width=width_total - 36)
        draw_text(d, start - (18 if rtl else -18), y + 44,
                  s["source"] % (co2.get("source") or ""), 14, lang,
                  color=MUTED, align=a_main, max_width=width_total - 36)
        y += 96

    # Footer
    d.line([left, PAGE_H - MARGIN - 30, right, PAGE_H - MARGIN - 30],
           fill=LINE, width=1)
    draw_text(d, start, PAGE_H - MARGIN - 18, s["footer"], 14, lang,
              color=MUTED, align=a_main)
    if plan_mode:
        draw_text(d, end, PAGE_H - MARGIN - 18, s["render"], 14, lang,
                  color=MUTED, align=a_opp)

    buf = io.BytesIO()
    page.save(buf, "PDF", resolution=DPI)
    return buf.getvalue()
